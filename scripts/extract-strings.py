"""Find the mod's translatable lines and report what each language file lacks.

The mod speaks its own English through src/Shared/Loc.cs, keyed by the English text itself (gettext style):

    Loc.T("You draw {0} cards: {1}", n, list)     a line, {0}, {1}... filled at run time
    Loc.P(n, "{0} card", "{0} cards")             a count: key "one|other" ("{0} card|{0} cards")
    Loc.Mark("Ore")                               a key kept in a table; its use site calls Loc.T(value)

This script scans src/Shared and games/*/Module for those calls with literal strings, then
  - writes assets/lang/en.json: every key, mapped to itself, in source order (the template for translators);
  - for every other assets/lang/<code>.json: lists the keys it lacks, the keys no longer in the source, and the
    translations whose {0} placeholders differ from the English.

    python scripts/extract-strings.py              write en.json, summary per language
    python scripts/extract-strings.py -v           also list every missing / stale / mismatched key
    python scripts/extract-strings.py --check      write nothing; exit 1 if en.json is out of date
    python scripts/extract-strings.py --where      also print where each key is first used (file:line), for context

Calls whose first string is not a literal (Loc.T(variable)) are not keys: such a value must be marked where it is
written (Loc.Mark) or be game text, which is translated by the game already.
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = os.path.join(REPO, "assets", "lang")
ROOTS = [os.path.join(REPO, "src", "Shared")] + [
    os.path.join(REPO, "games", g, "Module") for g in sorted(os.listdir(os.path.join(REPO, "games")))
]
NOTE_EN = ("The mod's own English lines, generated by scripts/extract-strings.py: do not edit by hand. "
           "To translate, copy this file to <game language code>.json (de-de, ru-ru, pt-br...) and replace each value.")

LIT = r'"((?:[^"\\\r\n]|\\.)*)"'
CALL_T = re.compile(r'\bLoc\.(?:T|Mark)\(\s*' + LIT)
# Loc.P(count, "one", "other"): the count expression holds no string literal.
CALL_P = re.compile(r'\bLoc\.P\([^";]*?,\s*' + LIT + r'\s*,\s*' + LIT)
PLACEHOLDER = re.compile(r'\{(\d+)(?:[,:][^}]*)?\}')


def unescape(s):
    out, i = [], 0
    simple = {'"': '"', "\\": "\\", "'": "'", "n": "\n", "t": "\t", "r": "\r", "0": "\0"}
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "u":
                out.append(chr(int(s[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append(simple.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def strip_comments(src):
    """Blank out // and /* */ comments (keeping string literals and line count), so commented code is no key."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c == '"':
            j = i + 1
            verbatim = i > 0 and src[i - 1] == "@"
            while j < n:
                if not verbatim and src[j] == "\\":
                    j += 2
                    continue
                if src[j] == '"':
                    if verbatim and j + 1 < n and src[j + 1] == '"':
                        j += 2
                        continue
                    break
                j += 1
            out.append(src[i:j + 1])
            i = j + 1
        elif c == "'" and i + 2 < n:
            j = src.find("'", i + 1 + (1 if src[i + 1] == "\\" else 0) + 1)
            j = j if j != -1 else i
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j == -1 else j
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j == -1 else j + 2
            out.append("\n" * src.count("\n", i, j))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def scan():
    keys = {}  # key -> first "file:line"
    for root in ROOTS:
        if not os.path.isdir(root):
            continue
        for d, dirs, files in os.walk(root):
            dirs[:] = sorted(x for x in dirs if x not in ("bin", "obj"))
            for f in sorted(files):
                if not f.endswith(".cs"):
                    continue
                path = os.path.join(d, f)
                with open(path, encoding="utf-8-sig") as fh:
                    src = strip_comments(fh.read())
                rel = os.path.relpath(path, REPO).replace("\\", "/")
                hits = []
                for m in CALL_T.finditer(src):
                    hits.append((m.start(), unescape(m.group(1))))
                for m in CALL_P.finditer(src):
                    hits.append((m.start(), unescape(m.group(1)) + "|" + unescape(m.group(2))))
                for pos, key in sorted(hits):
                    keys.setdefault(key, "%s:%d" % (rel, src.count("\n", 0, pos) + 1))
    return keys


def placeholders(text):
    return sorted(set(PLACEHOLDER.findall(text)))


def main():
    verbose = "-v" in sys.argv or "--verbose" in sys.argv
    check = "--check" in sys.argv
    keys = scan()
    en = {"_note": NOTE_EN}
    en.update((k, k) for k in keys)
    en_path = os.path.join(LANG, "en.json")
    text = json.dumps(en, ensure_ascii=False, indent=2) + "\n"
    old = None
    if os.path.exists(en_path):
        with open(en_path, encoding="utf-8") as fh:
            old = fh.read()
    if check:
        if old != text:
            print("assets/lang/en.json is out of date: run python scripts/extract-strings.py")
            return 1
    elif old != text:
        os.makedirs(LANG, exist_ok=True)
        with open(en_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("%d keys -> assets/lang/en.json%s" % (len(keys), "" if old != text or check else " (unchanged)"))
    if "--where" in sys.argv:
        for k, where in keys.items():
            print("%s	%s" % (where, json.dumps(k, ensure_ascii=False)))

    for f in sorted(os.listdir(LANG)) if os.path.isdir(LANG) else []:
        if not f.endswith(".json") or f == "en.json":
            continue
        with open(os.path.join(LANG, f), encoding="utf-8") as fh:
            try:
                tr = json.load(fh)
            except ValueError as e:
                print("%s: NOT VALID JSON: %s" % (f, e))
                continue
        missing = [k for k in keys if not tr.get(k)]
        stale = [k for k in tr if not k.startswith("_") and k not in keys]
        bad = []
        for k, v in tr.items():
            if k.startswith("_") or k not in keys or not isinstance(v, str) or not v:
                continue
            want = placeholders(k)
            forms = v.split("|") if "|" in k else [v]
            # A plural's forms may each drop {0} (Russian "одна карта"), never add one the English lacks.
            if "|" in k:
                if any(set(placeholders(x)) - set(want) for x in forms):
                    bad.append(k)
            elif placeholders(v) != want:
                bad.append(k)
        print("%s: %d of %d translated, %d missing, %d stale, %d placeholder mismatches"
              % (f, len(keys) - len(missing), len(keys), len(missing), len(stale), len(bad)))
        if verbose:
            for k in missing:
                print("  missing  %s  (%s)" % (json.dumps(k, ensure_ascii=False), keys[k]))
            for k in stale:
                print("  stale    %s" % json.dumps(k, ensure_ascii=False))
            for k in bad:
                print("  mismatch %s -> %s" % (json.dumps(k, ensure_ascii=False), json.dumps(tr[k], ensure_ascii=False)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
